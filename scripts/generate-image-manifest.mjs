import { readdirSync, statSync, writeFileSync } from "fs";
import { join } from "path";

const publicDir = join(process.cwd(), "public");
const images = [];

function walk(dir, prefix) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      walk(full, `${prefix}/${entry}`);
    } else if (/\.(jpe?g|png|gif|webp|avif|svg|ico)$/i.test(entry)) {
      images.push(`${prefix}/${entry}`);
    }
  }
}

walk(publicDir, "");

const content = `// AUTO-GENERATED by scripts/generate-image-manifest.mjs — do not edit.
// Lists every image shipped under public/ so the image-existence check works
// on the Cloudflare edge (no filesystem access) at runtime.
export const publicImages: ReadonlySet<string> = new Set([
${images.map((p) => `  ${JSON.stringify(p)},`).join("\n")}
]);
`;

writeFileSync(join(process.cwd(), "lib", "public-images.generated.ts"), content);
console.log(`Generated manifest with ${images.length} images`);
